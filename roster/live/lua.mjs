// ReplicatedStorage.ShinobiLive from the baked live moves (records/live/<id>/live.json) and their uploaded sheet ids
// (records/roblox4/ids.jsonl). node roster/live/lua.mjs <id> ...  ->  roster/studio/ShinobiLive.lua
import { readFileSync, writeFileSync } from "node:fs";
const ROOT = "C:/Users/yanni/Downloads/BuildAShinobi_JutsuModels/pixelfx/";
const ids = {};
for (const l of readFileSync(ROOT + "records/roblox4/ids.jsonl", "utf8").trim().split("\n")) for (const [k, v] of Object.entries(JSON.parse(l))) ids[k.split("/").pop()] = v;
const lua = (v) => {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "number") return String(Math.round(v * 1000) / 1000);
  if (typeof v === "boolean") return String(v);
  if (typeof v === "string") return JSON.stringify(v);
  if (Array.isArray(v)) return "{" + v.map(lua).join(", ") + "}";
  return "{" + Object.entries(v).map(([k, x]) => (/^[A-Za-z_]\w*$/.test(k) && k !== "until" ? k : `[${JSON.stringify(k)}]`) + " = " + lua(x)).join(", ") + "}";
};
// --noids: empty image ids (to test the server logic before the sheets are uploaded)
const NOIDS = process.argv.includes("--noids");
const book = (b) => ({ ...b, sheets: b.sheets.map((s) => { const id = ids[s.file] ?? (NOIDS ? "" : null); if (id === null) throw new Error("not uploaded: " + s.file); return { id, n: s.n }; }) });
let out = "-- GENERATED by roster/live/lua.mjs: the live moves of the training ground (no clips, no cutscenes).\n-- actor: the user + Susanoo layer per frame (cells cw x ch, feet at pivot), anchors per frame; fx: flipbooks with their\n-- origin at pivot; spawns/hits: the timeline the client shows and the server checks.\nlocal L = {}\n";
for (const id of process.argv.slice(2).filter((a) => !a.startsWith("--"))) {
  const j = JSON.parse(readFileSync(ROOT + `records/live/${id}/live.json`, "utf8"));
  const fx = Object.fromEntries(Object.entries(j.fx).map(([k, v]) => [k, book(v)]));
  out += `L[${JSON.stringify(id)}] = ${lua({ len: j.len, fps: j.fps, actor: book(j.actor), fx, spawns: j.spawns, hits: j.hits, onHit: j.onHit, onBlock: j.onBlock, sfx: j.sfx })}\n`;
}
out += "return L\n";
writeFileSync(ROOT + "roster/studio/ShinobiLive.lua", out);
console.log("roster/studio/ShinobiLive.lua", out.length, "bytes");
