// The PixelArena (summon moves on the 2.5D stage) for Studio: generates Defs (move numbers + book layout) and Roster
// (every variant's slots, with the live/summon ids) and wraps them with Sim, the client module and the server script
// into PixelArena.rbxmx in Studio's content folder:
//   ModuleScript PixelArena (client)  > Defs, Roster, Sim, Packs/<book>/P001...
//   Script PixelArenaServer
// Studio: game:GetObjects("rbxasset://models/_shinobi_tmp/PixelArena.rbxmx"). node roster/summon/push.mjs [moves...]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const R = "C:/Users/yanni/Downloads/BuildAShinobi_JutsuModels/pixelfx/roster/";
const VER = "C:/Users/yanni/AppData/Local/Roblox/Versions/version-8d7a1009c17e4ff8";
const CHUNK = 190000;
const moves = process.argv.slice(2).length ? process.argv.slice(2) : ["ninken", "gamabunta", "katsuyu", "enma", "kamatari", "baku", "gourd", "sage", "kurama", "statue"];
const lua = (v) => {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "number") return String(Math.round(v * 1000) / 1000);
  if (typeof v === "boolean") return String(v);
  if (typeof v === "string") return JSON.stringify(v);
  if (Array.isArray(v)) return "{" + v.map(lua).join(", ") + "}";
  return "{" + Object.entries(v).map(([k, x]) => (/^[A-Za-z_]\w*$/.test(k) && k !== "until" ? k : `[${JSON.stringify(k)}]`) + " = " + lua(x)).join(", ") + "}";
};
const src = (p) => { const s = readFileSync(p, "utf8").replace(/\r\n/g, "\n"); if (s.includes("]]>")) throw new Error(p + " contains ]]>"); return s; };
let ref = 0;
const item = (cls, name, inner = "", props = "") => `<Item class="${cls}" referent="RBX${ref++}">\n<Properties>\n<string name="Name">${name}</string>\n${props}</Properties>\n${inner}</Item>\n`;
const mod = (name, code, inner = "") => item("ModuleScript", name, inner, `<ProtectedString name="Source"><![CDATA[${code}]]></ProtectedString>\n`);

const defs = { moves: {}, books: {}, dogs: [] };
let packs = "";
for (const m of moves) {
  const j = JSON.parse(readFileSync(R + `summon/packs/${m}.json`, "utf8"));
  for (const mv of j.moves ?? [j.move]) defs.moves[mv.id] = mv;
  for (const [name, b] of Object.entries(j.books)) {
    const { b64, raw, ...meta } = b;
    defs.books[name] = meta;
    if (name.startsWith("dog_")) defs.dogs.push(name.slice(4));
    let parts = "";
    for (let i = 0, k = 1; i < b64.length; i += CHUNK, k++) parts += item("StringValue", "P" + String(k).padStart(3, "0"), "", `<string name="Value">${b64.slice(i, i + CHUNK)}</string>\n`);
    packs += item("Folder", name, parts);
  }
}
// the order the dogs come out of the ground in the server's ring (Bull first, as in the anime's pack)
const ORDER = ["bull", "pakkun", "uhei", "shiba", "bisuke", "akino", "guruko", "urushi"];
defs.dogs.sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b));
const defsLua = "-- GENERATED by roster/summon/push.mjs: summon move numbers (studs, seconds) and the packed books' layout.\nreturn " + lua(defs) + "\n";

const roster = JSON.parse(readFileSync(R + "roster.json", "utf8"));
const vs = roster.variants.map((v) => ({ id: v.id, era: v.era, cell: v.cell, name: v.name, form: v.form,
  slots: v.slots.map((s) => ({ name: s.name, kind: s.kind, status: s.status, live: s.params?.live ?? null, summon: s.params?.summon ?? null })) }));
let rosterLua = "-- GENERATED by roster/summon/push.mjs from roster/roster.json (81 variants, 195 slots; Shippuden duplicates replaced).\nlocal R = { list = " + lua(vs) + " }\nR.byId = {}\nfor _, v in ipairs(R.list) do R.byId[v.id] = v end\nreturn R\n";

const xml = `<roblox version="4">\n` +
  mod("PixelArena", src(R + "summon/studio/PixelArena.lua"), mod("Defs", defsLua) + mod("Roster", rosterLua) + mod("Sim", src(R + "summon/studio/PixelArenaSim.lua")) + item("Folder", "Packs", packs)) +
  item("Script", "PixelArenaServer", "", `<ProtectedString name="Source"><![CDATA[${src(R + "summon/studio/PixelArenaServer.server.lua")}]]></ProtectedString>\n`) +
  `</roblox>\n`;
mkdirSync(VER + "/content/models/_shinobi_tmp", { recursive: true });
writeFileSync(VER + "/content/models/_shinobi_tmp/PixelArena.rbxmx", xml);
// vfx test: the same two items plus its 2.5D training stage (a LocalScript for StarterPlayerScripts)
const stage = item("LocalScript", "PixelArenaStage", "", `<ProtectedString name="Source"><![CDATA[${src(R + "summon/studio/PixelArenaStage.client.lua")}]]></ProtectedString>\n`);
writeFileSync(VER + "/content/models/_shinobi_tmp/PixelArenaVfx.rbxmx", xml.replace("</roblox>\n", stage + "</roblox>\n"));
console.log("PixelArena.rbxmx", xml.length, "chars; books", Object.keys(defs.books).length, "dogs", defs.dogs.join(","));
