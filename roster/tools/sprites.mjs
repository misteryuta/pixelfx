// ReplicatedStorage.ShinobiSprites: each variant's own fight-scene atlas (records/chars/<name>_atlas.json + its
// uploaded asset id in records/roblox4/ids.jsonl). node roster/tools/sprites.mjs
import { readFileSync, writeFileSync } from "node:fs";
const ROOT = "C:/Users/yanni/Downloads/BuildAShinobi_JutsuModels/pixelfx/";
const ids = {};
for (const l of readFileSync(ROOT + "records/roblox4/ids.jsonl", "utf8").trim().split("\n")) for (const [k, v] of Object.entries(JSON.parse(l))) ids[k.split("/").pop()] = v;
// which variants wear which atlas
const WEAR = { itachi: ["shippuden/itachi-uchiha-mangekyo-sharingan"] };
let lua = "-- GENERATED by roster/tools/sprites.mjs: the variants' own fight-scene atlases (from the user's turnarounds).\nlocal S = {}\n";
for (const [name, vids] of Object.entries(WEAR)) {
  const a = JSON.parse(readFileSync(ROOT + `records/chars/${name}_atlas.json`, "utf8")), id = ids[`${name}_atlas.png`];
  if (!id) throw new Error("no uploaded atlas for " + name);
  const rows = Object.entries(a.rows).map(([k, [r, n, loop]]) => `${k} = { ${r}, ${n}${loop ? ", true" : ""} }`).join(", ");
  lua += `S.${name} = { image = "${id}", cw = ${a.cw}, ch = ${a.ch}, fx = ${a.fx}, fy = ${a.fy}, rows = { ${rows} } }\n`;
  for (const v of vids) lua += `S["${v}"] = S.${name}\n`;
}
lua += "return S\n";
writeFileSync(ROOT + "roster/studio/ShinobiSprites.lua", lua);
console.log(lua);
